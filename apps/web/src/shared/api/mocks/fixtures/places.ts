import type { Place, SavedPlace, WeeklyHours } from '@where-is-hype/core';

function dailyHours(open: string, close: string): WeeklyHours {
  const day = { open, close };
  return {
    mon: day,
    tue: day,
    wed: day,
    thu: day,
    fri: day,
    sat: day,
    sun: day,
  };
}

function barWeekendHours(
  weekdayOpen: string,
  weekdayClose: string,
  weekendOpen: string,
  weekendClose: string,
): WeeklyHours {
  const weekday = { open: weekdayOpen, close: weekdayClose };
  const weekend = { open: weekendOpen, close: weekendClose };
  return {
    mon: weekday,
    tue: weekday,
    wed: weekday,
    thu: weekday,
    fri: weekend,
    sat: weekend,
    sun: weekday,
  };
}


def _daily_hours(open_time: str, close_time: str) -> WeeklyHours:
    day = DayHours(open=open_time, close=close_time)
    return WeeklyHours(
        mon=day,
        tue=day,
        wed=day,
        thu=day,
        fri=day,
        sat=day,
        sun=day,
    )


def _bar_weekend_hours(
    weekday_open: str,
    weekday_close: str,
    weekend_open: str,
    weekend_close: str,
) -> WeeklyHours:
    weekday = DayHours(open=weekday_open, close=weekday_close)
    weekend = DayHours(open=weekend_open, close=weekend_close)
    return WeeklyHours(
        mon=weekday,
        tue=weekday,
        wed=weekday,
        thu=weekday,
        fri=weekend,
        sat=weekend,
        sun=weekday,
    )


def _make_place(  # noqa: PLR0913, PLR0917
    place_id: str,
    name: str,
    place_type: PlaceType,
    address: str,
    metro_name: str,
    metro_dist: int,
    lat: float,
    lng: float,
    hours: WeeklyHours | None,
    avg_check: int | None,
    yandex_org_id: str | None,
    raw_category: str | None = None,
) -> Place:
    return Place(
        id=place_id,
        name=name,
        type=place_type,
        address=address,
        metro=PlaceMetro(name=metro_name, distanceM=metro_dist),
        location=Location(lat=lat, lng=lng),
        hours=hours,
        avgCheck=avg_check,
        yandexOrgId=yandex_org_id,
        rawCategory=raw_category,
    )


